#[component]
fn BuildCard(b: &'static Build) -> Element {
    let shape = match b.media {
        Media::Portrait => "portrait",
        Media::Landscape => "landscape",
    };
    let mut class = format!("build t-{}", b.theme.slug);
    if b.lead {
        class.push_str(" build--lead");
    }
    // A landscape recording keeps the full card width and stacks; squeezed into the
    // side column it would be unreadable at any size.
    if matches!(b.media, Media::Landscape) {
        class.push_str(" build--wide");
    }

    rsx! {
        // The card is an article, not a link. Wrapping a pager in an <a> would mean every
        // "next" click also navigated away, and suppressing that with preventDefault is a
        // fight you lose on keyboard and middle-click. The title carries the link instead.
        article { class: "{class}",
            div { class: "media", "data-media": "{shape}",
                div { class: "bezel",
                    video {
                        class: "shot",
                        src: "{b.video}",
                        poster: "{b.poster}",
                        autoplay: true,
                        muted: true,
                        "loop": "true",
                        playsinline: true,
                        preload: if b.lead { "auto" } else { "metadata" },
                        "aria-label": "{b.alt}",
                    }
                }
            }
            div { class: "panel",
                div { class: "top",
                    h3 { a { class: "title-link", href: "{href(b)}", "{b.name}" } }
                    span { class: "num", "{b.cycle}" }
                    if let Some(f) = b.flag {
                        span { class: "flag", "{f}" }
                    }
                }
                p { class: "stat", "{b.stat}" }

                // Every slide is rendered visible. The pager script collapses them on load,
                // so crawlers, print, Reader mode and a scripting-off screen reader all get
                // the full text, and a JS failure degrades to a longer card rather than a
                // blank one.
                div { class: "slides", role: "group", "aria-live": "polite",
                    for (i, s) in b.slides.iter().enumerate() {
                        section {
                            class: "slide",
                            "data-i": "{i}",
                            h4 { "{s.title}" }
                            p { "{s.lead}" }
                            if !s.points.is_empty() {
                                ul {
                                    for pt in s.points {
                                        li { "{pt}" }
                                    }
                                }
                            }
                        }
                    }
                }

                div { class: "tags",
                    for t in b.tags {
                        span { class: if t.live { "tag live" } else { "tag" }, "{t.label}" }
                    }
                }

                // Inert until the script upgrades it; hidden entirely without JS.
                nav { class: "pager", "aria-label": "{b.name} detail",
                    button { class: "pg pg-prev", "type": "button", "aria-label": "Previous", "‹" }
                    span { class: "dots",
                        for (i, s) in b.slides.iter().enumerate() {
                            button {
                                class: "dot",
                                "type": "button",
                                "data-go": "{i}",
                                "aria-label": "{s.title}",
                            }
                        }
                    }
                    button { class: "pg pg-next", "type": "button", "aria-label": "Next", "›" }
                }
            }
        }
    }
}

#[component]
fn ExportStory() -> Element {
    rsx! {
        div { class: "pull t-housecheck",
            h3 { "The export that found its own hole" }
            p {
                "A tenant lawyer can read a building's violations on any city website. What they
                 cannot do is put that reading in front of a court, because a printout is
                 unverifiable. HouseCheck's export carries an append-only hash chain and an Ed25519
                 signature, so opposing counsel can re-check it offline — without trusting us and
                 without reaching our servers."
            }
            p {
                "The part I am prouder of than the cryptography: while verifying it in production I
                 wrote an independent verifier in another language, and found that "
                span { class: "hi", "signing alone was not enough" }
                ". A forger who rewrites a row, recomputes the whole chain and signs it with their
                 own keypair produces a document that verifies as intact — because it is internally
                 consistent. A row rewritten to "
                code { "NO VIOLATIONS OF ANY KIND AT THIS ADDRESS" }
                " passed cleanly."
            }
            p {
                "The fix was publishing the public key at a stable endpoint, so a reader has
                 something to compare against. That hole existed because the code's own comment
                 said "
                em { "“compare with the published one”" }
                " while nothing published it."
            }
        }
    }
}

#[component]
fn RustArgument() -> Element {
    rsx! {
        div { class: "pull",
            h3 { "Three of the four have a property a type system can defend." }
            p {
                "HouseCheck signs a document a court might rely on. SiteAssure keeps a safety log
                 that has to stay tamper-evident. Resona promises that audio never leaves the
                 machine. In each case the product's whole claim is a guarantee about what the
                 program will "
                em { "not" }
                " do — and a guarantee is easier to hold when the compiler is checking it than when
                 a test suite is remembering to."
            }
            p {
                "The practical payoff is boring and real: a read-only SQLite artefact baked into a
                 container with "
                span { class: "hi", "no database server and no connection pool" }
                "; a desktop app that ships one binary; "
                span { class: "hi", "149 tests and clippy-clean" }
                " on the current build, with correctness bugs re-measured across the whole dataset
                 rather than spot-checked. This page is the smallest example: its four card themes
                 are Rust values, and a "
                code { "const" }
                " assertion refuses to compile any theme whose text falls below WCAG 4.5:1 on its
                 own background."
            }
        }
    }
}

#[component]
fn Stack(rows: &'static [Row], top: bool) -> Element {
    rsx! {
        dl {
            class: "stack",
            style: if top { "margin-top:26px" } else { "" },
            for r in rows {
                div { class: "row",
                    dt { "{r.dt}" }
                    dd { "{r.dd}" }
                }
            }
        }
    }
}
