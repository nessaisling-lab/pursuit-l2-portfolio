//! Renders the portfolio landing page: Dioxus RSX in, one static HTML file out.
//!
//! Deliberately *not* `dx bundle --ssg`. That path ships a WASM bundle and hydrates,
//! and it is broken for exactly this deployment shape -- GitHub Pages serves this repo
//! under `/pursuit-l2-portfolio/`, and `base_path` with `dx bundle` is DioxusLabs/dioxus
//! #3942, open with no fix. Rendering a VirtualDom to a String sidesteps all of it:
//! no router, no hydration, no bundle, no base path to get wrong. The output is the
//! same single self-contained file the page has always been, and the browser does not
//! know or care that Rust produced it.

mod content;
mod theme;

use content::*;
use dioxus::prelude::*;
use theme::*;

const STYLE: &str = include_str!("../assets/style.css");
const FIELD_JS: &str = include_str!("../assets/field.js");
const PAGER_JS: &str = include_str!("../assets/pager.js");
const FONTS: &str = "https://fonts.googleapis.com/css2?family=Archivo:wght@700\
&family=Fraunces:opsz,wght@9..144,400;9..144,600;9..144,700\
&family=Inter:wght@400;500;600&family=JetBrains+Mono:wght@400;500\
&family=Manrope:wght@800&family=Source+Serif+4:opsz,wght@8..60,600&display=swap";

fn main() -> std::io::Result<()> {
    let body = dioxus_ssr::render_element(rsx! { Page {} });
    let css = STYLE.replace("/*@THEMES@*/", &themes_css());

    let html = format!(
        "<!doctype html>\n\
         <html lang=\"en\">\n\
         <head>\n\
         <meta charset=\"utf-8\">\n\
         <meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">\n\
         <title>Stan (Aisling) Leiva-Davila — Pursuit L2</title>\n\
         <meta name=\"description\" content=\"Four cycles, four shipped products. Pursuit AI-Native Builder, inaugural cohort.\">\n\
         <link rel=\"preconnect\" href=\"https://fonts.googleapis.com\">\n\
         <link rel=\"preconnect\" href=\"https://fonts.gstatic.com\" crossorigin>\n\
         <link href=\"{FONTS}\" rel=\"stylesheet\">\n\
         <style>\n{css}\n</style>\n\
         </head>\n\
         <body>\n\
         <canvas id=\"field\" aria-hidden=\"true\"></canvas>\n\
         {body}\n\
         <script>\n{PAGER_JS}\n</script>\n\
         <script>\n{FIELD_JS}\n</script>\n\
         </body>\n\
         </html>\n"
    );

    let out = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../index.html");
    std::fs::write(&out, &html)?;
    eprintln!(
        "wrote {} ({} bytes, {} themes, {} builds)",
        out.display(),
        html.len(),
        THEMES.len(),
        BUILDS.len()
    );
    Ok(())
}

/// Height every portrait recording is sized to fill, in CSS pixels. The bezel width
/// for each app is derived from this and that app's measured aspect, so three videos
/// with different shapes still land on one horizontal rhythm.
/// 400 rather than 460: at two columns on a 1440px viewport a card is ~570px wide, and
/// a 283px bezel left HouseCheck's panel at 254px — narrow enough that the text wrapped
/// into a taller column than its own video, which put the empty band back.
const MEDIA_TARGET_H: f64 = 400.0;

/// Emits the per-theme custom-property blocks.
///
/// The contrast figure in each comment is *computed*, not typed, so those comments
/// cannot drift away from the colours they describe. A hand-written comment claiming
/// a ratio nobody rechecks is the same failure as HouseCheck's export comment that
/// said "compare with the published one" while nothing published it.
fn themes_css() -> String {
    let mut s = String::from(
        "/* ── the four themes ──────────────────────────────────────────────────────\n\
         \x20  GENERATED by site/src/theme.rs -- edit the Rust, not this block.\n\
         \x20  Hex values were sampled from this repo's own screenshots. Contrast ratios\n\
         \x20  in the comments are computed from those values at build time, and every\n\
         \x20  pairing is additionally held to WCAG 4.5:1 by a const assertion, so an\n\
         \x20  unreadable theme fails the build rather than shipping.\n\
         \x20  ───────────────────────────────────────────────────────────────────────── */\n",
    );

    for t in THEMES {
        let ink_ratio = contrast_x100(t.ink, t.surface) as f64 / 100.0;
        let accent_ratio = contrast_x100(t.accent, t.surface) as f64 / 100.0;
        // Width that lands this app's recording at MEDIA_TARGET_H, from the real asset
        // aspect rather than eyeballed, so every portrait video fills to one height.
        let bezel = (MEDIA_TARGET_H * t.video_aspect).round() as i32;
        s.push_str(&format!(
            "\n.t-{slug}{{\n\
             \x20 --surface:{surface};\n\
             \x20 --card-ink:{ink};                    /* {ink_ratio:.2}:1 */\n\
             \x20 --card-ink-2:{ink2};\n\
             \x20 --accent:{accent};                      /* {accent_ratio:.2}:1 */\n\
             \x20 --chip:{chip};\n\
             \x20 --chip-ink:{chip_ink};\n\
             \x20 --edge:{edge};\n\
             \x20 --face:{face};\n\
             \x20 --face-size:{fsize};--face-track:{ftrack};\n\
             }}\n\
             .t-{slug} .media{{--shot-bg:{shot_bg};--bezel-w:{bezel}px}}\n",
            slug = t.slug,
            surface = t.surface.hex(),
            ink = t.ink.hex(),
            ink2 = t.ink.alpha(t.ink_alpha),
            accent = t.accent.hex(),
            chip = t.chip,
            chip_ink = t.chip_ink.hex(),
            edge = t.ink.alpha(t.edge_alpha),
            face = t.face,
            fsize = t.face_size,
            ftrack = t.face_track,
            shot_bg = t.shot_bg.hex(),
        ));
        if let Some(live) = t.live_ink {
            s.push_str(&format!(
                ".t-{} .tag.live{{color:{}}}   /* {:.2}:1 inside the dark chip */\n",
                t.slug,
                live.hex(),
                contrast_x100(live, Rgb(0x3B, 0x3B, 0x3D)) as f64 / 100.0,
            ));
        }
        if let Some(h) = t.hover {
            s.push_str(&format!(".t-{}:hover{{border-color:{}}}\n", t.slug, h.hex()));
        }
    }
    s
}

